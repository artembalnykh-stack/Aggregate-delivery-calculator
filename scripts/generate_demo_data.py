def main() -> None:
    DATA_DIR.mkdir(exist_ok=True)
    wb = Workbook()
    wb.remove(wb.active)

    products = build_products()
    vehicles = build_vehicles()
    warehouses = [{"ID": i, "Название": n, "Город": g, "Адрес": a,
                   "Широта": lat, "Долгота": lon, "Активен": "Да"}
                  for i, n, g, a, lat, lon in WAREHOUSES]
    dests = [{"ID": i, "Название": n, "Широта": lat, "Долгота": lon}
             for i, n, lat, lon in DESTINATIONS]

    write_sheet(wb, "Товары", PRODUCT_HEADERS, products,
                title="Прайс-лист «Нейростройтранс» (демо)")
    write_sheet(wb, "Самосвалы", VEHICLE_HEADERS, vehicles,
                title="Автопарк (демо)", header_row=3)
    write_sheet(wb, "Склады", WAREHOUSE_HEADERS, warehouses,
                title="Склады отгрузки", header_row=2)
    write_sheet(wb, "Пункты доставки", DEST_HEADERS, dests,
                title="Справочник пунктов доставки", header_row=3)
    write_sheet(wb, "Тарифы", TARIFF_HEADERS,
                [{"Параметр": k, "Значение": v, "Комментарий": c} for k, v, c in TARIFFS],
                title="Тарифы доставки")
    write_sheet(wb, "Правила", RULE_HEADERS,
                [{"Параметр": k, "Значение": v, "Комментарий": c} for k, v, c in RULES],
                title="Бизнес-правила расчёта")
    write_sheet(wb, "Совместимость", COMPAT_HEADERS,
                [{"Тип груза": g, "Тип кузова": t, "Допустимо": d} for g, t, d in COMPAT],
                title="Совместимость типа груза и типа кузова")

    (DATA_DIR / "exports").mkdir(exist_ok=True)
    wb.save(OUT)
    print(f"OK: {OUT}  товаров={len(products)} машин={len(vehicles)}")


if __name__ == "__main__":
    main()
