def write_sheet(wb: Workbook, name: str, headers: list[str], rows: list[dict],
                title: str | None = None, header_row: int = 2) -> None:
    ws = wb.create_sheet(name)
    style_sheet(ws, header_row, headers, title)
    for r, row in enumerate(rows, start=header_row + 1):
        for c, h in enumerate(headers, start=1):
            ws.cell(row=r, column=c, value=row.get(h))
