def style_sheet(ws, header_row: int, headers: list[str], title: str | None = None) -> None:
    """Пишет необязательный титул (со сдвигом — проверка автопоиска шапки) и шапку."""
    offset = 0
    if title:
        ws.cell(row=1, column=1, value=title).font = TITLE_FONT
        ws.merge_cells(start_row=1, start_column=1,
                       end_row=1, end_column=max(len(headers), 3))
        offset = 1
    for col, name in enumerate(headers, start=1):
        c = ws.cell(row=header_row, column=col, value=name)
        c.fill = HEADER_FILL
        c.font = HEADER_FONT
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
    for col in range(1, len(headers) + 1):
        ws.column_dimensions[get_column_letter(col)].width = 16
    ws.column_dimensions["B"].width = 42
    ws.freeze_panes = ws.cell(row=header_row + 1, column=1)


