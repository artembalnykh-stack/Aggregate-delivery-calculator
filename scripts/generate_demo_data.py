def build_products() -> list[dict]:
    rows: list[dict] = []
    art = 0

    def add(name, cat, unit, price, mass, vol, gtype, active="Да"):
        nonlocal art
        art += 1
        rows.append({
            "Артикул": f"NS{art:04d}", "Наименование": name, "Категория": cat,
            "Единица измерения": unit, "Цена, руб": price,
            "Масса единицы, кг": round(mass, 3), "Объём единицы, м³": round(vol, 4),
            "Тип груза": gtype, "Активен": active, "Дата цены": date.today(),
        })

    # насыпные / миксерные: цена за м³, масса ед. = плотность т/м³ → кг
    for name, cat, dens, price, _ in LOOSE:
        add(name, cat, "м³", price, dens * 1000, 1.0, "Навалочный")
    for name, cat, dens, price, _ in BULK_CEMENT:
        add(name, cat, "м³", price, dens * 1000, 1.0, "Навалочный")
    for name, cat, dens, price, _ in MIXER:
        add(name, cat, "м³", price, dens * 1000, 1.0, "Миксерный")
        add(name + " (м3 с учётом тары)", cat, "м³", price, dens * 1000, 1.0,
            "Миксерный", active="Да")

    # штучные
    for name, cat, unit, mass, vol, price in BAGGED:
        add(name, cat, unit, price, mass, vol, "Штучный")
    for name, cat, unit, mass, vol, price in BRICKS:
        add(name, cat, unit, price, mass, vol, "Штучный")
    for name, cat, unit, mass, vol, price in WALL_BLOCKS:
        add(name, cat, unit, price, mass, vol, "Штучный")
    for name, cat, unit, mass, vol, price in MISC:
        add(name, cat, unit, price, mass, vol, "Штучный")

    # вариации предложений для насыпных (разные «складские предложения»)
    base_loose = [r for r in rows if r["Единица измерения"] == "м³"
                  and r["Тип груза"] == "Навалочный"]
    for src in base_loose:
        for suffix, delta in ((" фракц. А", 0.07), (" фракц. В", 0.13),
                              (" (поставщик 2)", 0.05), (" (розница)", 0.18)):
            art += 1
            rows.append({
                "Артикул": f"NS{art:04d}",
                "Наименование": src["Наименование"] + suffix,
                "Категория": src["Категория"],
                "Единица измерения": "м³",
                "Цена, руб": round(src["Цена, руб"] * (1 + delta), -1),
                "Масса единицы, кг": src["Масса единицы, кг"],
                "Объём единицы, м³": 1.0,
                "Тип груза": "Навалочный",
                "Активен": random.choice(["Да", "Да", "Да", "Нет"]),
                "Дата цены": date.today(),
            })

    base_unit = [r for r in rows if r["Тип груза"] == "Штучный"]
    for src in base_unit:
        for suffix, delta in ((" (эконом)", 0.88), (" (премиум)", 1.15)):
            art += 1
            rows.append({
                "Артикул": f"NS{art:04d}",
                "Наименование": src["Наименование"] + suffix,
                "Категория": src["Категория"],
                "Единица измерения": src["Единица измерения"],
                "Цена, руб": round(src["Цена, руб"] * delta),
                "Масса единицы, кг": src["Масса единицы, кг"],
                "Объём единицы, м³": src["Объём единицы, м³"],
                "Тип груза": "Штучный",
                "Активен": random.choice(["Да", "Да", "Да", "Нет"]),
                "Дата цены": date.today(),
            })

    random.shuffle(rows)
    return rows


